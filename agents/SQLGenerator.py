import json
from typing import List, Dict, Any
from models.lessons import lessons
from models.content.text import TextContent
from logger.config import logger
import uuid


class SQLGenerator:
    """
    Agent responsible for generating SQL INSERT queries for lessons table
    """
    
    def __init__(self):
        self.table_name = "lessons"
        logger.info("SQLGenerator agent initialized")
    
    def generate_insert_query(self, lesson_data: lessons) -> str:
        """
        Generate SQL INSERT query for a single lesson
        
        Args:
            lesson_data: lessons model instance
            
        Returns:
            str: SQL INSERT query
        """
        try:
            logger.info(f"Generating SQL INSERT query for lesson: {lesson_data.title}")
            
            # Convert sections to JSONB format
            sections_jsonb = self._convert_sections_to_jsonb(lesson_data.sections)
            sections_jsonb_str = json.dumps(sections_jsonb)
            # Escape single quotes for SQL
            sections_jsonb_str = sections_jsonb_str.replace("'", "''")
            
            # Create the INSERT query
            content_jsonb_str = json.dumps({"sections": sections_jsonb})
            content_jsonb_str = content_jsonb_str.replace("'", "''")
            query = f"""
INSERT INTO {self.table_name} (
    id,
    course_id,
    title,
    is_active,
    content,
    created_at,
    updated_at
) VALUES (
    '{uuid.uuid4()}',
    '{lesson_data.course_id}',
    '{self._escape_sql_string(lesson_data.title)}',
    {str(lesson_data.is_active).lower()},
    '{content_jsonb_str}'::jsonb,
    NOW(),
    NOW()
);
"""
            logger.info(f"Successfully generated SQL INSERT query for lesson: {lesson_data.title}")
            return query.strip()
            
        except Exception as e:
            logger.error(f"Error generating SQL INSERT query: {e}")
            raise
    
    def generate_batch_insert_queries(self, lessons_data: List[lessons]) -> List[str]:
        """
        Generate SQL INSERT queries for lessons
        
        Args:
            lessons_data: List of lessons model instances (typically single lesson with all sections)
            
        Returns:
            List[str]: List of SQL INSERT queries
        """
        try:
            logger.info(f"Generating SQL INSERT queries for {len(lessons_data)} lessons")
            
            queries = []
            for lesson in lessons_data:
                query = self.generate_insert_query(lesson)
                queries.append(query)
            
            logger.info(f"Successfully generated {len(queries)} SQL INSERT queries")
            return queries
            
        except Exception as e:
            logger.error(f"Error generating batch SQL INSERT queries: {e}")
            raise
    
    def _convert_sections_to_jsonb(self, sections: List[TextContent]) -> List[Dict[str, Any]]:
        """
        Convert sections to JSONB-compatible format
        
        Args:
            sections: List of TextContent objects
            
        Returns:
            List[Dict[str, Any]]: JSONB-compatible sections
        """
        try:
            jsonb_sections = []
            for section in sections:
                section_dict = {
                    "type": section.type,
                    "content": section.content,
                    "title": section.title
                }
                jsonb_sections.append(section_dict)
            
            logger.debug(f"Converted {len(jsonb_sections)} sections to JSONB format")
            return jsonb_sections
            
        except Exception as e:
            logger.error(f"Error converting sections to JSONB format: {e}")
            raise
    
    def _escape_sql_string(self, text: str) -> str:
        """
        Escape single quotes in SQL strings
        
        Args:
            text: Text to escape
            
        Returns:
            str: Escaped text
        """
        return text.replace("'", "''")
    
    def save_queries_to_file(self, queries: List[str], filename: str = "sql_queries.sql") -> str:
        """
        Save SQL queries to a file
        
        Args:
            queries: List of SQL queries
            filename: Output filename
            
        Returns:
            str: Path to saved file
        """
        try:
            filepath = f"output/{filename}"
            
            with open(filepath, "w", encoding="utf-8") as f:
                f.write("-- Generated SQL INSERT queries for lessons table\n")
                f.write("-- Generated by SQLGenerator agent\n\n")
                
                for i, query in enumerate(queries, 1):
                    f.write(f"-- Query {i}\n")
                    f.write(query)
                    f.write("\n\n")
            
            logger.info(f"Saved {len(queries)} SQL queries to {filepath}")
            return filepath
            
        except Exception as e:
            logger.error(f"Error saving SQL queries to file: {e}")
            raise 